// The dead-time fade estimator: what it can recover, what it refuses, and what
// it reports when the model is wrong. Synthetic data here comes from an
// **independent** implementation of the model, so these tests check the fit
// rather than checking the code against itself.
// 死区淡出估计器：能恢复什么、拒绝什么、模型不对时报告什么。这里的合成数据来自模型的**独立**实现，
// 所以这些用例检查的是拟合本身，而不是代码自己对自己。

#include <cmath>
#include <cstdio>
#include <initializer_list>

#include <gtest/gtest.h>

#include <foc/core/deadtime.hpp>

namespace {

namespace core = foc::core;

constexpr float kRs = 0.5F;
constexpr float kDeadtimeV = 0.48F;

/// [en] The identification model, written out here from the physics: a
/// *rotating* current of amplitude `I`
///      sees the fundamental of the phase losses `dV*clamp(i/If)`, i.e.
///      `(4/pi)*dV` along the current, so the vector relation collapses to one
///      scalar equation `|v| = rs*|i| + (4/pi)*dV*clamp(|i|/If)`. [zh]
///      辨识模型，这里按物理独立写出：**旋转**电流（幅值 `I`）看到的是每相损失
///      `dV·clamp(i/If)` 的 基波，即沿电流方向的
///      `(4/π)·dV`，于是矢量关系退化成一个标量方程
///      `|v| = rs·|i| + (4/π)·dV·clamp(|i|/If)`。
auto loss_magnitude(float i_mag, float fade, float v_dead) -> float {
  const auto clamp_unit = [](float value) -> float {
    if (value > 1.0F) {
      return 1.0F;
    }
    return value;
  };
  return (4.0F / core::kPi<float>)*v_dead * clamp_unit(std::fabs(i_mag) / fade);
}

/// [en] A swept set of settled operating points for a given truth. [zh]
/// 给定真值下的一组稳定工作点。
auto sweep(core::DeadTimeFadeEstimator &estimator, float true_fade, float rs,
           float gain = 1.0F, float noise = 0.0F) -> int {
  int used = 0;
  unsigned state = 0x1234567U;
  for (int k = 1; k <= 24; ++k) {
    // Currents from 2 mA to 0.2 A, log-spaced: the knee of the fade has to be
    // inside the sweep. 电流从 2 mA 到 0.2 A
    // 对数分布：淡出的拐点必须落在扫描范围内。
    const float fraction = static_cast<float>(k) / 24.0F;
    const float i =
        static_cast<float>(0.002F * std::pow(10.0F, fraction * 2.0F));
    const float v =
        static_cast<float>((rs * i) + loss_magnitude(i, true_fade, kDeadtimeV));

    // Deterministic pseudo-noise, so the test is reproducible without a random
    // engine. Integer xorshift, like the plant's noise knob: a float LCG grows
    // without bound and turns the samples into NaN after four steps.
    // 确定性伪噪声，测试可在不用随机引擎的情况下复现。整数 xorshift，与 plant
    // 的 噪声旋钮一致：浮点 LCG 会无界增长，四步之后就把样本变成 NaN。
    float jitter = 0.0F;
    if (noise > 0.0F) {
      state ^= state << 13U;
      state ^= state >> 17U;
      state ^= state << 5U;
      jitter = noise * ((static_cast<float>(state % 2001U) / 1000.0F) - 1.0F);
    }
    if (estimator.add(gain * v, i + jitter)) {
      ++used;
    }
  }
  return used;
}

} // namespace

TEST(DeadTimeFade, RecoversAKnownFadeFromACleanSweep) {
  // Mechanics first: with data generated by the very model being fitted, the
  // answer has to come back.
  // 先验机制：数据由被拟合的那个模型自己生成，答案必须回得来。
  core::DeadTimeFadeEstimator estimator(
      core::DeadTimeFadeEstimator::Config{kRs, kDeadtimeV, 0.25F});
  const int used = sweep(estimator, 0.02F, kRs);
  const core::DeadTimeFadeEstimator::Result result = estimator.solve();

  std::printf("\n[deadtime] clean sweep: %d samples -> fade %.5f A, residual "
              "%.5f V, valid %d\n",
              used, static_cast<double>(result.fade_a),
              static_cast<double>(result.residual_v),
              static_cast<int>(result.valid));

  EXPECT_EQ(24, used);
  EXPECT_TRUE(result.valid);
  EXPECT_NEAR(0.02F, result.fade_a, 0.002F) << "5 % of the truth";
  EXPECT_LT(result.residual_v, 0.03F * kDeadtimeV);
}

TEST(DeadTimeFade, TracksTheTruthAcrossThreeDecades) {
  // A fit that always returns the same number would pass the test above. This
  // one would not. 一个永远返回同一个数的拟合能通过上面那条；这条不能。
  for (const float truth : {0.003F, 0.02F, 0.15F}) {
    core::DeadTimeFadeEstimator estimator(
        core::DeadTimeFadeEstimator::Config{kRs, kDeadtimeV, 0.25F});
    static_cast<void>(sweep(estimator, truth, kRs));
    const core::DeadTimeFadeEstimator::Result result = estimator.solve();
    std::printf("[deadtime] truth %.4f A -> fade %.5f A (ratio %.3f), residual "
                "%.6f V\n",
                static_cast<double>(truth), static_cast<double>(result.fade_a),
                static_cast<double>(result.fade_a / truth),
                static_cast<double>(result.residual_v));
    EXPECT_TRUE(result.valid);
    EXPECT_LT(std::fabs(result.fade_a / truth - 1.0F), 0.20F)
        << "truth " << truth;
  }
}

TEST(DeadTimeFade, AnIdealStepComesBackAsAVeryNarrowFade) {
  // The `sign()` model is the limit of the ramp at zero width, so the fit must
  // walk to the bottom of the grid rather than inventing a width. `sign()`
  // 模型是斜坡在零宽度处的极限，所以拟合必须走到网格底部，而不是编一个宽度出来。
  core::DeadTimeFadeEstimator estimator(
      core::DeadTimeFadeEstimator::Config{kRs, kDeadtimeV, 0.25F});
  static_cast<void>(sweep(estimator, 1.0e-9F, kRs));
  const core::DeadTimeFadeEstimator::Result result = estimator.solve();
  std::printf("[deadtime] ideal step -> fade %.6f A, residual %.6f V\n",
              static_cast<double>(result.fade_a),
              static_cast<double>(result.residual_v));
  EXPECT_TRUE(result.valid);
  EXPECT_LT(result.fade_a, 0.002F) << "the grid floor, i.e. effectively a step";
}

TEST(DeadTimeFade, RefusesToIdentifyFromTooFewSamples) {
  // Five points can be fitted by anything. The estimator says so instead of
  // returning a number. 五个点什么都能拟合。估计器如实说明，而不是返回一个数。
  core::DeadTimeFadeEstimator estimator(
      core::DeadTimeFadeEstimator::Config{kRs, kDeadtimeV, 0.25F});
  for (int k = 1; k <= 5; ++k) {
    const float i = 0.01F * static_cast<float>(k);
    static_cast<void>(estimator.add(
        static_cast<float>((kRs * i) + loss_magnitude(i, 0.02F, kDeadtimeV)),
        i));
  }
  const core::DeadTimeFadeEstimator::Result result = estimator.solve();
  EXPECT_EQ(5, estimator.samples());
  EXPECT_FALSE(result.valid);
}

TEST(DeadTimeFade, ReportsAWrongResistanceInsteadOfAbsorbingItSilently) {
  // The one thing this fit cannot separate: an error in `rs` and an error in
  // the fade both bend the same curve. So the honest contract is that the
  // *residual* grows, and the caller is told. A 2x `rs` error has to be
  // visible; a 10 % one is allowed to hide (documented on the class).
  // 这个拟合分不开的一件事：`rs`
  // 的错与淡出的错弯的是同一条曲线。所以诚实的契约是**残差**变大并告知
  // 调用方。2 倍的 `rs` 错误必须可见；10 % 的允许被吸收（类文档已写明）。
  core::DeadTimeFadeEstimator good(
      core::DeadTimeFadeEstimator::Config{kRs, kDeadtimeV, 0.25F});
  static_cast<void>(sweep(good, 0.02F, kRs));
  const core::DeadTimeFadeEstimator::Result good_result = good.solve();

  // The fit is told twice the true resistance while the data was produced with
  // the truth. 拟合被告知两倍的真电阻，而数据是按真值产生的。
  core::DeadTimeFadeEstimator wrong(
      core::DeadTimeFadeEstimator::Config{2.0F * kRs, kDeadtimeV, 0.25F});
  static_cast<void>(sweep(wrong, 0.02F, kRs));
  const core::DeadTimeFadeEstimator::Result wrong_result = wrong.solve();

  std::printf(
      "[deadtime] residual with the true rs %.5f V, with 2x rs %.5f V (%.0f %% "
      "of the dead-time "
      "voltage)\n",
      static_cast<double>(good_result.residual_v),
      static_cast<double>(wrong_result.residual_v),
      static_cast<double>(100.0F * wrong_result.residual_v / kDeadtimeV));

  EXPECT_LT(good_result.residual_v, 0.03F * kDeadtimeV);
  EXPECT_GT(wrong_result.residual_v, 0.06F * kDeadtimeV)
      << "the inconsistency has to show up somewhere";
}

TEST(DeadTimeFade, SurvivesTheCurrentSensorsNoiseFloor) {
  // Identification that only works on noiseless data is a laboratory result. 10
  // mA of noise against a 20 mA fade is roughly what a 10 A shunt gives at 0.1
  // % of full scale. 只在无噪声数据上成立的辨识是实验室结果。10 mA 噪声对 20 mA
  // 的淡出，大约就是 10 A 分流器在满量程 0.1 % 处的水平。
  core::DeadTimeFadeEstimator estimator(
      core::DeadTimeFadeEstimator::Config{kRs, kDeadtimeV, 0.25F});
  static_cast<void>(sweep(estimator, 0.02F, kRs, 1.0F, 0.010F));
  const core::DeadTimeFadeEstimator::Result result = estimator.solve();
  std::printf("[deadtime] with 10 mA noise: fade %.5f A (truth 0.02), residual "
              "%.5f V\n",
              static_cast<double>(result.fade_a),
              static_cast<double>(result.residual_v));
  EXPECT_TRUE(result.valid);
  EXPECT_NEAR(0.02F, result.fade_a, 0.006F);
}

TEST(DeadTimeFade, IsDeterministicAndGuardsItsConfiguration) {
  // Same samples, same answer -- a commissioning step that is not reproducible
  // cannot be debugged. 同样的样本、同样的答案——不可复现的整定步骤无法排障。
  core::DeadTimeFadeEstimator first(
      core::DeadTimeFadeEstimator::Config{kRs, kDeadtimeV, 0.25F});
  core::DeadTimeFadeEstimator second(
      core::DeadTimeFadeEstimator::Config{kRs, kDeadtimeV, 0.25F});
  static_cast<void>(sweep(first, 0.02F, kRs));
  static_cast<void>(sweep(second, 0.02F, kRs));
  EXPECT_FLOAT_EQ(first.solve().fade_a, second.solve().fade_a);
  EXPECT_FLOAT_EQ(first.solve().residual_v, second.solve().residual_v);

  // No dead time to identify: every sample is refused rather than fitted.
  // 没有死区可辨识：每个采样都被拒绝，而不是被拟合。
  core::DeadTimeFadeEstimator none(
      core::DeadTimeFadeEstimator::Config{kRs, 0.0F, 0.25F});
  EXPECT_FALSE(none.add(1.0F, 0.5F));
  EXPECT_EQ(0, none.samples());
  EXPECT_FALSE(none.solve().valid);

  // Samples above the limit (thermal, or outside the model's validity) are
  // dropped. 超过上限的采样（热、或超出模型有效范围）被丢弃。
  core::DeadTimeFadeEstimator capped(
      core::DeadTimeFadeEstimator::Config{kRs, kDeadtimeV, 0.05F});
  EXPECT_TRUE(capped.add(1.0F, 0.04F));
  EXPECT_FALSE(capped.add(2.0F, 0.06F));
  EXPECT_EQ(1, capped.samples());
}
