# Report
# --------------------------------------------------------------------------------------------------------------
def report_standstill(capture=None):
    currents = [0.20, 0.32, 0.50, 0.80, 1.25, 2.00]
    if capture is None:
        voltages = standstill_sweep(currents)
        source = "synthetic sweep"
    else:
        currents, voltages = [], []
        with open(capture, newline="", encoding="utf-8") as handle:
            for row in csv.DictReader(handle):
                currents.append(float(row["i_a"]))
                voltages.append(float(row["v"]))
        source = capture

    rs_fit, loss_fit = np.polyfit(currents, voltages, 1)  # slope is Rs, intercept is the constant loss
    rs_lib, loss_lib, residual_lib, valid_lib, samples_lib = foc.rs_estimate(params(), voltages, currents)

    print(f"standstill sweep ({source}, {len(currents)} points)")
    print(f"  injected          : Rs {RS:.6f} ohm, loss {LOSS_V:.4f} V")
    print(f"  numpy polyfit     : Rs {rs_fit:.6f} ohm, loss {loss_fit:.4f} V")
    print(f"  foc.rs_estimate   : Rs {rs_lib:.6f} ohm, loss {loss_lib:.4f} V, residual {residual_lib:.2e} V, "
          f"valid {valid_lib}, {samples_lib} sample(s)")

    ok = True
    if abs(rs_fit - RS) > 0.005 * RS:
        print(f"  FAIL: scipy/numpy Rs is {abs(rs_fit - RS) / RS * 100:.2f} % off the injected value")
        ok = False
    if not valid_lib or abs(rs_lib - RS) > 0.005 * RS:
        print(f"  FAIL: the library's Rs is {abs(rs_lib - RS) / RS * 100:.2f} % off, or it refused the sweep")
        ok = False
    if abs(rs_fit - rs_lib) > 0.005 * RS:
        print(f"  FAIL: the two routes disagree by {abs(rs_fit - rs_lib) / RS * 100:.2f} %")
        ok = False
    return ok


def report_flux():
    speeds = [200.0 / POLE_PAIRS, 350.0 / POLE_PAIRS, 600.0 / POLE_PAIRS, 900.0 / POLE_PAIRS, 1400.0 / POLE_PAIRS]
    pairs = zero_current_sweep(speeds)
    omega = np.array([p[0] for p in pairs])
    voltage = np.array([p[1] for p in pairs])

    psi_fit, offset_fit = np.polyfit(omega, voltage, 1)
    psi_lib, offset_lib, residual_lib, valid_lib, samples_lib = foc.flux_estimate(
        params(), list(omega), list(voltage), [0.0] * len(pairs))

    print()
    print(f"zero-current speed sweep ({len(pairs)} points, {omega[0]:.0f} to {omega[-1]:.0f} rad/s electrical)")
    print(f"  injected          : psi_f {PSI_F:.6f} Wb, offset {FLUX_OFFSET_V:.4f} V")
    print(f"  numpy polyfit     : psi_f {psi_fit:.6f} Wb, offset {offset_fit:.4f} V")
    print(f"  foc.flux_estimate : psi_f {psi_lib:.6f} Wb, offset {offset_lib:.4f} V, residual {residual_lib:.2e} V, "
          f"valid {valid_lib}, {samples_lib} sample(s)")

    ok = True
    for name, value in (("scipy/numpy", psi_fit), ("the library's", psi_lib)):
        if abs(value - PSI_F) > 0.01 * PSI_F:
            print(f"  FAIL: {name} psi_f is {abs(value - PSI_F) / PSI_F * 100:.2f} % off the injected value")
            ok = False
    if abs(psi_fit - psi_lib) > 0.01 * PSI_F:
        print(f"  FAIL: the two routes disagree by {abs(psi_fit - psi_lib) / PSI_F * 100:.2f} %")
        ok = False
    return ok


def report_step_and_identifiability():
    v_step = 4.0
    samples = 200  # 10 ms at the control rate: several time constants, since L/R is 0.8 ms

    print()
    print(f"d-axis voltage step, {v_step:.1f} V, {samples} samples at {DT_SAMPLE * 1e6:.0f} us")
    print(f"{'machine':>10} {'angle err':>10} {'Rs err %':>9} {'Ld err %':>9} {'Ls/Ld leak':>11} {'condition':>10}")

    ok = True
    for label, ld, lq in (("Lq = Ld", LD, LD), ("Lq = 2 Ld", LD, 2.0 * LD)):
        for angle_deg in (0.0, 2.0, 5.0, 10.0):
            angle = math.radians(angle_deg)
            trace = axis_step(v_step, ld, angle, samples, lq)
            rs_fit, ind_fit, _, condition = fit_axis_step(trace, v_step)
            leak = float(np.max(np.abs(trace[:, 2]))) / float(np.max(np.abs(trace[:, 1])))
            rs_error = (rs_fit - RS) / RS * 100.0
            ind_error = (ind_fit - ld) / ld * 100.0
            print(f"{label:>10} {angle_deg:9.0f}d {rs_error:8.2f}% {ind_error:8.2f}% {leak:10.2f}% {condition:10.1f}")
            if angle_deg == 0.0 and abs(ind_error) > 2.0:
                print(f"  FAIL: Ld is {ind_error:.2f} % off at zero angle error")
                ok = False

    # The correlation between the two parameters, from the same Jacobian: near +-1 means the capture only identified a
    # combination of them.
    # 同一 Jacobian 给出的两参数相关系数：接近 ±1 意味着这次采样只辨识出了它们的某个组合。
    trace = axis_step(v_step, LD, 0.0, samples)
    t = trace[:, 0]
    vd = v_step

    def model(theta):
        rs, ind = theta
        return (vd / rs) * (1.0 - np.exp(-t * rs / ind))

    def jac(theta):
        rs, ind = theta
        eps_rs, eps_ind = rs * 1e-6, ind * 1e-6
        base = model(theta)
        return np.stack([(model([rs + eps_rs, ind]) - base) / eps_rs,
                         (model([rs, ind + eps_ind]) - base) / eps_ind], axis=1)

    j = jac([RS, LD])
    cov = np.linalg.inv(j.T @ j)
    scale = np.sqrt(np.diag(cov))
    correlation = cov[0, 1] / (scale[0] * scale[1])

    print()
    print(f"identifiability: Rs/L correlation {correlation:+.4f} over {t[-1] * 1e3:.1f} ms")
    short = axis_step(v_step, LD, 0.0, 20)  # one time constant
    _, ind_short, _, condition_short = fit_axis_step(short, v_step)
    print(f"                 over one time constant ({20 * DT_SAMPLE * 1e3:.1f} ms) the condition number rises to "
          f"{condition_short:.1f} and Ld lands {(ind_short - LD) / LD * 100.0:+.1f} % off")

    # Noiseless data hides ill-conditioning: a well-determined combination looks like two well-determined parameters.
    # Adding the noise a shunt and an ADC actually have is what turns the condition number into a visible spread.
    # 无噪声数据会把病态性藏起来：一个被很好确定的组合，看起来像两个被很好确定的参数。加上分流器与 ADC 真实存在的噪声，
    # 条件数才变成看得见的离散。
    rng = np.random.default_rng(20261028)
    noise_a = 0.020
    print()
    print(f"with {noise_a * 1e3:.0f} mA rms of measurement noise, 8 repeats:")
    print(f"{'capture':>18} {'Rs spread %':>12} {'Ld spread %':>12}")
    for label, count in (("1 time constant", 20), ("10 time constants", 200)):
        rs_values, ind_values = [], []
        for _ in range(8):
            trace = axis_step(v_step, LD, 0.0, count)
            noisy = trace.copy()
            noisy[:, 1] += rng.normal(0.0, noise_a, size=noisy.shape[0])
            rs_fit, ind_fit, _, _ = fit_axis_step(noisy, v_step)
            rs_values.append(rs_fit)
            ind_values.append(ind_fit)
        rs_spread = (max(rs_values) - min(rs_values)) / RS * 100.0
        ind_spread = (max(ind_values) - min(ind_values)) / LD * 100.0
        print(f"{label:>18} {rs_spread:11.2f}% {ind_spread:11.2f}%")
    return ok


def main() -> int:
    parser = argparse.ArgumentParser(description="Identify Rs, psi_f and the axis inductances, and say what is visible.")
    parser.add_argument("--capture", help="CSV with i_a,v columns to use instead of the synthetic standstill sweep")
    args = parser.parse_args()

    ok = report_standstill(args.capture)
    ok = report_flux() and ok
    ok = report_step_and_identifiability() and ok

    print()
    print("OK: the library and an independent least-squares fit agree, and the limits of the capture are quantified"
          if ok else "NOT OK")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
