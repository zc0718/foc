"""Identifying the machine from a commissioning sweep, and asking what the sweep can actually see.

Two things are measured here, and the second one matters more.

The first is agreement: the library's closed-form estimators (`foc.rs_estimate`, `foc.flux_estimate`, reached through the
C ABI) and an independent `scipy.optimize.least_squares` fit of the same data. They solve the problem two different ways,
so agreement is a cross-check on both. The samples are synthetic -- generated by integrating a plant whose parameters
are known -- which is what makes the answer checkable at all; the same script reads a real capture instead by pointing
`--capture` at a CSV, so nothing here depends on the data being fake.

The second is identifiability, and it is the part a commissioning routine usually omits. A step response gives `Rs` and
an inductance only *jointly*: the curve depends on `Rs/L` through the time constant and on `Rs` through its final value,
so a short capture separates them only weakly -- and with no noise that weakness is invisible, which is the trap worth
demonstrating. A rotor-angle error does something different from what is usually assumed: it attenuates the excitation
by `cos(delta)` and biases **both** `Rs` and `L` by `1/cos(delta)`, while at standstill it does *not* mix `Ld` with
`Lq` at all (the axes are decoupled when the speed is zero, so a salient machine gives the same numbers as a
non-salient one). Separating the two inductances needs speed or a second excitation axis, not a better standstill fit.
Both effects are measured below rather than asserted to be fine.

    source workspace/materials/.venv/bin/activate
    LIB=$(find ~/.conan2/p/b -name "foc_python.cpython-310*.so" | head -1)
    PYTHONPATH=$(dirname "$LIB") python benchmark/script/identify_parameters.py

Criteria, written before the run:
  * standstill sweep: `Rs` within 0.5 % of the injected value, and the library and scipy fits within 0.5 % of each other
  * zero-current sweep: `psi_f` within 1 % of the injected value, same agreement requirement
  * d-axis step: `Ld` within 2 % at zero angle error, and the fit must report its own conditioning
  * the angle-error sweep is reported, not asserted: it exists to show the size of the leak, and an assertion there
    would only encode whatever number this particular plant happens to give
"""

import argparse
import csv
import math
import sys

import numpy as np
from scipy.optimize import least_squares

import foc_python as foc

# The machine under test: the SIL nameplate, in SI units.
RS, LD, LQ, PSI_F = 0.5, 4.0e-4, 4.0e-4, 0.05 / (1.5 * 7.0)
POLE_PAIRS = 7
LOSS_V = 0.64  # the constant voltage a real inverter adds: dead time, device drops
FLUX_OFFSET_V = 0.30  # a voltage-sense offset, which the flux fit must absorb in its intercept

DT_SAMPLE = 50e-6
DT_INTEGRATION = 1e-6


def params():
    p = foc.MotorParams()
    p.rs, p.ld, p.lq = RS, LD, LQ
    p.kt, p.j, p.b, p.pole_pairs = 0.05, 1e-5, 1e-6, POLE_PAIRS
    return p


# --------------------------------------------------------------------------------------------------------------
# Experiments
# --------------------------------------------------------------------------------------------------------------
def standstill_sweep(currents):
    """Settled (voltage, current) pairs, the way a commissioning sweep produces them: `v = Rs*i + loss`."""
    return [(RS * i) + LOSS_V for i in currents]


def zero_current_sweep(speeds_mech):
    """Settled (speed, voltage) pairs at zero current: `v = psi_f*omega_e + offset`."""
    out = []
    for speed in speeds_mech:
        omega_e = POLE_PAIRS * speed
        out.append((omega_e, (PSI_F * omega_e) + FLUX_OFFSET_V))
    return out


def axis_step(v_step, ld, angle_error_rad, samples, lq=None):
    """One voltage step on the commanded d axis, integrated and sampled at the control rate.

    The rotor sits at `angle_error_rad` away from the commanded frame, so the excitation is rotated relative to the
    machine: what reaches the true d axis is `v*cos(error)` and what reaches the true q axis is `-v*sin(error)`.
    命令 d 轴上加一个电压阶跃，积分后按控制周期采样。转子偏离命令坐标系 `angle_error_rad`，于是加在真实 d 轴上的
    是 `v*cos(error)`、真实 q 轴上的是 `-v*sin(error)`。
    """
    lq = ld if lq is None else lq
    samples_per_control = int(round(DT_SAMPLE / DT_INTEGRATION))
    total = samples + 1
    vd = v_step * math.cos(angle_error_rad)
    vq = -v_step * math.sin(angle_error_rad)

    psi_d, psi_q = 0.0, 0.0
    t = 0.0
    trace = []
    for k in range(total * samples_per_control):
        i_d = psi_d / ld
        i_q = psi_q / lq
        psi_d += DT_INTEGRATION * (vd - (RS * i_d))
        psi_q += DT_INTEGRATION * (vq - (RS * i_q))
        t += DT_INTEGRATION
        if (k + 1) % samples_per_control == 0:
            trace.append((t, i_d, i_q))
    return np.array(trace)


def fit_axis_step(trace, v_step, assumed_angle_rad=0.0):
    """Least-squares fit of (Rs, L) to a sampled d-axis step.

    The fit is told only what a commissioning routine would know: the voltage it commanded and the current it measured.
    It assumes the excitation reached the d axis in full, which is exactly the assumption a rotor-angle error breaks.
    拟合只知道勘定程序会知道的事：它命令的电压与它测到的电流。它假定励磁完整地落在 d 轴上——而这正是转子角度误差
    所破坏的假定。
    """
    t = trace[:, 0]
    i_d = trace[:, 1]
    vd = v_step * math.cos(assumed_angle_rad)

    def model(theta):
        rs, ind = theta
        return (vd / rs) * (1.0 - np.exp(-t * rs / ind))

    result = least_squares(lambda theta: model(theta) - i_d, x0=[RS * 1.2, LD * 0.8], method="trf",
                           x_scale=[RS, LD])
    rs, ind = result.x

    # Identifiability, in the only form that can be trusted: the singular values of the Jacobian at the solution. A pair
    # of nearly dependent columns means the two parameters trade off against each other, and the estimate is then a
    # statement about their product rather than about either one.
    # 可辨识性，只采信一种形式：解处 Jacobian 的奇异值。两列近似相关意味着两个参数在互相抵消，此时估计值说的是它们的
    # 乘积，而不是其中任何一个。
    jac = result.jac
    singular = np.linalg.svd(jac, compute_uv=False)
    condition = float(singular[0] / singular[-1]) if singular[-1] > 0 else math.inf
    return rs, ind, float(np.sqrt(np.mean(result.fun ** 2))), condition


